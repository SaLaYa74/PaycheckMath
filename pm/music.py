"""Original, catchy background beats for Reels, synthesized from scratch.

Nothing here uses samples, loops or third-party audio: every sound is generated by this code,
so there are no licensing or copyright claims on it. What makes it catchy:
  - a short melodic HOOK (a hummable 1-bar riff) that repeats, with a variation the 2nd time
  - a real groove per style (house / trap / funk-pop), punchy kick + clap
  - "pumping" sidechain: music ducks under each kick, the classic dance-track bounce
  - echo on the clap and lead for space
Each Reel gets a style, key, tempo and hook picked from its post key, so Reels don't all sound alike.
"""
import math
import random
import struct
import wave

RATE = 22050
TAU = 2 * math.pi

# minor pentatonic + octave (semitones) — almost any combination of these sounds good
PENTA = [0, 3, 5, 7, 10, 12, 15]
# 16-step hook rhythms; numbers index PENTA, None = rest. Short, repetitive, singable.
HOOKS = [
    [0, None, 2, None, 3, None, 2, 3, None, 4, None, 3, 2, None, 0, None],
    [4, None, 4, 3, None, 2, None, 3, None, None, 2, None, 0, None, 2, None],
    [0, 2, None, 3, None, 4, None, 3, 2, None, 0, None, None, 2, 3, None],
    [3, None, 3, None, 4, 3, None, 2, None, 0, None, 2, None, 3, None, None],
    [5, None, 4, None, 3, None, 4, None, 3, 2, None, 0, None, None, 0, None],
]
PROGRESSIONS = [[0, -4, 3, -2], [0, 5, -4, -5], [0, -2, -4, -2], [0, 3, -2, 5]]
KEYS = [57, 55, 52, 53, 50, 59]          # A, G, E, F, D, B (MIDI)
STYLES = {"house": 122, "trap": 140, "funk": 104}


def _hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def _square(f, t):      # warm square-ish lead (odd harmonics)
    x = TAU * f * t
    return math.sin(x) + math.sin(3 * x) / 3 + math.sin(5 * x) / 6


def _saw(f, t):         # bright saw-ish chord stab
    x = TAU * f * t
    return sum(math.sin(k * x) / k for k in range(1, 6))


class _Bus:
    def __init__(self, n):
        self.b = [0.0] * n
        self.n = n

    def add(self, start_s, dur_s, fn):
        s0 = int(start_s * RATE)
        for i in range(max(0, s0), min(self.n, s0 + int(dur_s * RATE))):
            self.b[i] += fn((i - s0) / RATE)

    def echo(self, delay_s, fb, mix):
        d = int(delay_s * RATE)
        out = self.b[:]
        for i in range(d, self.n):
            out[i] += out[i - d] * fb
        self.b = [x + (y - x) * mix for x, y in zip(self.b, out)]


def make_beat(path, seconds, seed="sharpcharts"):
    rnd = random.Random(seed)
    style = rnd.choice(list(STYLES))
    bpm = STYLES[style] + rnd.choice([-4, -2, 0, 2])
    key = rnd.choice(KEYS)
    prog = rnd.choice(PROGRESSIONS)
    hook = rnd.choice(HOOKS)
    beat = 60.0 / bpm
    step = beat / 4                                  # 16th note
    n = int(seconds * RATE)
    drums, bass, music, lead = _Bus(n), _Bus(n), _Bus(n), _Bus(n)
    noise = [rnd.uniform(-1, 1) for _ in range(RATE)]
    hp = lambda t, off=0: noise[(int(t * RATE) + off) % RATE] - noise[(int(t * RATE) + off - 1) % RATE]
    kick = lambda amp: (lambda t: amp * math.sin(TAU * (48 * t + 110 / 28 * (1 - math.exp(-28 * t)))) * math.exp(-7 * t))
    clap = lambda t: 0.55 * hp(t, 900) * (math.exp(-30 * t) + 0.6 * math.exp(-30 * max(0, t - 0.012)))
    hat = lambda amp, dec: (lambda t: amp * hp(t, 4000) * math.exp(-dec * t))

    bars = int(seconds / (beat * 4)) + 1
    kicks = []
    for bar in range(bars):
        b0 = bar * beat * 4
        root = key + prog[bar % len(prog)]
        chord = [root, root + 3, root + 7]
        second_half = bar % 2 == 1
        # ---------------- drums
        if style == "house":
            for q in range(4):
                kicks.append(b0 + q * beat)
                drums.add(b0 + q * beat, 0.35, kick(0.95))
                drums.add(b0 + q * beat + beat / 2, 0.12, hat(0.16, 25))          # open-ish offbeat hat
            for q in (1, 3):
                drums.add(b0 + q * beat, 0.25, clap)
        elif style == "trap":
            for s16 in (0, 6, 10) + ((13,) if second_half else ()):
                kicks.append(b0 + s16 * step)
                drums.add(b0 + s16 * step, 0.4, kick(1.0))
            drums.add(b0 + 2 * beat, 0.3, clap)                                   # half-time snare on 3
            for s16 in range(16):
                drums.add(b0 + s16 * step, 0.05, hat(0.10, 90))
            roll = b0 + 3 * beat + 2 * step                                        # signature hi-hat roll
            for r in range(6):
                drums.add(roll + r * step / 3, 0.03, hat(0.08, 120))
        else:  # funk
            for s16 in (0, 7, 10):
                kicks.append(b0 + s16 * step)
                drums.add(b0 + s16 * step, 0.35, kick(0.9))
            for q in (1, 3):
                drums.add(b0 + q * beat, 0.25, clap)
            for s16 in range(0, 16, 2):
                drums.add(b0 + s16 * step, 0.06, hat(0.12 if s16 % 4 else 0.06, 60))
        # ---------------- bass
        fb = _hz(root - 24)
        if style == "house":                                                      # offbeat pumping bass
            for q in range(4):
                bass.add(b0 + q * beat + beat / 2, beat * 0.45,
                         lambda t, f=fb: 0.42 * math.sin(TAU * f * t) * min(1, t * 80) * math.exp(-4 * t))
        elif style == "trap":                                                     # long 808 with a pitch glide
            bass.add(b0, beat * 3.8, lambda t, f=fb: 0.5 * math.sin(TAU * f * (t + 0.04 * (1 - math.exp(-6 * t)) / 6))
                     * min(1, t * 60) * math.exp(-0.7 * t))
        else:                                                                     # funky octave-jumping bass
            for s16, o in ((0, 0), (3, 12), (6, 0), (8, 0), (11, 12), (14, 7)):
                f = _hz(root - 24 + o)
                bass.add(b0 + s16 * step, step * 1.6, lambda t, f=f: 0.38 * math.sin(TAU * f * t) * min(1, t * 90) * math.exp(-6 * t))
        # ---------------- chord stabs (syncopated)
        for s16 in ((2, 6, 10, 14) if style != "trap" else (0, 8)):
            dur = step * (1.4 if style != "trap" else 7)
            for m in chord:
                f = _hz(m)
                music.add(b0 + s16 * step, dur, lambda t, f=f, d=dur: 0.035 * _saw(f, t) * min(1, t * 120)
                          * math.exp(-(7 if style != "trap" else 1.2) * t) * min(1, (d - t) * 40))
        # ---------------- the hook
        for s16, deg in enumerate(hook):
            if deg is None:
                continue
            if second_half and s16 >= 12:                                         # variation: lift the ending
                deg = min(deg + 1, len(PENTA) - 1)
            f = _hz(key + 12 + PENTA[deg])
            lead.add(b0 + s16 * step, step * 1.8, lambda t, f=f: 0.16 * _square(f * (1 + 0.004 * math.sin(TAU * 5.5 * t)), t)
                     * min(1, t * 150) * math.exp(-5.5 * t))

    lead.echo(beat * 0.75, 0.32, 0.45)
    drums.echo(beat * 0.5, 0.18, 0.15)
    # sidechain pump: everything except drums ducks right after each kick
    duck = [1.0] * n
    for k in kicks:
        s0 = int(k * RATE)
        for i in range(max(0, s0), min(n, s0 + int(0.22 * RATE))):
            duck[i] = min(duck[i], 0.35 + 0.65 * ((i - s0) / (0.22 * RATE)) ** 1.6)
    mix = [d + duck[i] * (b + m + l) for i, (d, b, m, l) in enumerate(zip(drums.b, bass.b, music.b, lead.b))]
    peak = max(1e-6, max(abs(x) for x in mix))
    fade_in, fade_out = int(0.05 * RATE), int(0.8 * RATE)
    frames = bytearray()
    for i, x in enumerate(mix):
        g = min(1.0, i / fade_in, (n - i) / fade_out)
        frames += struct.pack("<h", int(math.tanh(1.4 * x / peak) / math.tanh(1.4) * 0.92 * g * 32767))
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(bytes(frames))
    return {"style": style, "bpm": bpm, "key": key}
